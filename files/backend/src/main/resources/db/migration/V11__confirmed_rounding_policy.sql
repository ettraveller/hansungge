-- A-2 는 2026-08-24 에 확정됐다: 최종 판매가를 <b>백원 단위로 올림</b>(CEIL_100).
--   예) 51,232.6 → 51,300   512,326 → 512,400
--
-- 그런데 V1 의 시드는 아직 'TBD' 였다. 그러면 새로 올린 환경은 설정을 찾지 못해
-- PriceRoundingResolver 가 <b>임시 기본값(WON_FLOOR, 원 단위 버림)</b>으로 계산한다.
-- 기동은 정상이고 경고 로그 한 줄만 남기 때문에, 아무도 눈치채지 못한 채
-- 확정 정책과 다른 금액이 고객에게 나간다 — 실제로 이 결함은 장바구니 통합테스트가
-- "601,300 이 나와야 하는데 601,250 이 나온다"로 잡아냈다.
--
-- 운영자가 화면에서 값을 넣어주기를 기다리지 않는다. 확정된 정책은 코드와 함께
-- 배포되어야 한다.
--
-- ※ 이미 CEIL_100 으로 바꿔 둔 환경(개발 DB)에서는 값이 같으므로 변화가 없다.
--    운영자가 의도적으로 다른 값을 넣어 둔 경우까지 덮어쓰지는 않도록, 아직 미확정
--    표시인 'TBD' 인 행만 바꾼다.
-- =====================================================================

UPDATE system_settings
SET value       = 'CEIL_100',
    description = '최종가 반올림 정책. A-2 확정(2026-08-24): 백원 단위 올림',
    updated_at  = now()
WHERE key = 'PRICE_ROUNDING_MODE'
  AND value = 'TBD';

