-- =====================================================================
-- V33__product_made_to_order.sql : 주문제작 상품을 상품별로 표시한다
--
-- 2026-10-30. 두 가지가 동시에 막혀 있었다.
--
-- ---------------------------------------------------------------------
-- 1. 전자상거래법 제17조 제2항 — 청약철회 제한은 상품별로 고지해야 한다
--
-- 주문서에서 청약철회 제한 동의를 받고 있지만(V29), 어떤 상품이 그 대상인지
-- 가리는 값이 없었다. 법이 요구하는 것은 "주문을 받아 개별 생산되는 재화"라는
-- 사실을 <b>그 상품을 사기 전에</b> 알리는 것이다. 사이트 전체에 한 줄 적어
-- 두는 것으로는 "이 상품이 그것인지"를 고객이 알 수 없다.
--
-- 고지 없이 제한하면 제한이 무효가 되어, 제작이 끝난 주문도 환불해야 한다.
--
-- ---------------------------------------------------------------------
-- 2. PG 심사 — 배송기간이 상품페이지에 있어야 한다
--
-- "구매자가 배송기간을 인지할 수 있도록 상품페이지 내에 명확히 기재되어
-- 있어야 함". 재고를 들고 있는 골드바와 주문을 받아 만드는 반지는 기간이
-- 몇 배 차이가 나므로, 한 문장으로 적으면 둘 중 하나가 거짓이 된다.
--
--   재고 보유   결제 확인 후 영업일 7일 이내
--   주문제작    제작 4~5주 + 배송 영업일 7일 — 결제일부터 최대 6주
--
-- ---------------------------------------------------------------------
-- 왜 기간이 아니라 BOOLEAN 인가
--
-- 상품마다 주수를 넣게 하면 상품을 올릴 때마다 판단해야 하고, 6주를 넘기는
-- 값이 들어가면 PG 정책 위반이 된다 — 그것을 막는 검사를 코드 양쪽에 두는
-- 것보다, 기간은 두 갈래로 고정하고 상품은 어느 갈래인지만 고르게 하는 쪽이
-- 어긋날 자리가 없다. 실제로 기간이 다른 품목이 생기면 그때 컬럼을 늘린다.
--
-- 문구 자체는 DB 에 넣지 않는다. 이용약관·환불약관·상품페이지가 같은 말을
-- 해야 하는데 DB 에 두면 화면마다 따로 읽어 가며 한쪽만 낡는다.
-- =====================================================================

ALTER TABLE products
    ADD COLUMN made_to_order BOOLEAN NOT NULL DEFAULT false;

-- DEFAULT 를 남긴다 (V31 의 kind 와 반대다).
--
-- kind 는 어느 갈래인지 넣는 코드가 반드시 정해야 하는 값이라 기본값을 뗐다.
-- 여기는 다르다. 빠뜨렸을 때 안전한 쪽이 분명하다 — false 로 들어가면
-- "재고 보유"로 읽히고, 그 약속(영업일 7일)을 못 지키면 고객이 문의한다.
-- true 가 기본이면 재고가 있는 상품까지 청약철회가 제한된 것으로 고지되어,
-- 고객의 권리를 근거 없이 깎는다. 조용히 틀리는 쪽이 더 위험하다.

COMMENT ON COLUMN products.made_to_order IS
    '주문을 받아 개별 생산하는 상품인가. true 면 상세에 제작 기간과 '
    '청약철회 제한을 함께 고지한다 (전자상거래법 §17②①)';
