-- =====================================================================
-- V35 — 18K·14K 환산 비율을 살 때 / 팔 때로 나눈다
--
-- 정책 행은 원래부터 금속×방향으로 따로 있었다(market_price_policies). 그런데 화면과
-- 서비스가 비율 한 칸만 받아 두 행에 같은 값을 넣고 있었다. 그 결과 <b>판매 비율이
-- 매입에도 적용되어</b> 매입가가 실제 영업 기준보다 높게 고시됐다.
--
--   2026-11-03 운영값 예 — 18K 매입 513,810원/돈 (24K 매입 622,800 × 0.825)
--                영업 기준  18K 매입 454,644원/돈 (24K 매입 622,800 × 0.73)
--   1돈당 59,166원을 더 쳐주고 사들이고 있었다.
--
-- 영업이 확정한 공식(2026-11-03)
--   18K 판매 = 24K 판매 × 0.825   18K 매입 = 24K 매입 × 0.73
--   14K 판매 = 24K 판매 × 0.6435  14K 매입 = 24K 매입 × 0.565
--   (판매가에는 상품별 공임비가 더해진다 — 시세가 아니라 상품 가격 계산 쪽이다)
--
-- 판매 비율은 이미 맞으므로 건드리지 않는다. 매입 행만 고친다.
--
-- ⚠️ 이 마이그레이션은 <b>설정만</b> 바꾼다. 이미 나가 있는 고시값은 그대로다 —
--    시세 이력은 append-only 라 지난 고시를 고칠 수 없고, 고쳐서도 안 된다.
--    배포 후 관리자가 24K 를 한 번 고시하면(또는 환산 설정을 저장하면) 새 비율로
--    18K·14K 가 다시 발행되면서 바로잡힌다.
-- =====================================================================

UPDATE market_price_policies
   SET derive_ratio = 0.7300,
       updated_by   = 'system',
       updated_at   = now()
 WHERE metal_type = 'GOLD_18K'
   AND price_side = 'BUY'
   AND mode = 'DERIVED';

UPDATE market_price_policies
   SET derive_ratio = 0.5650,
       updated_by   = 'system',
       updated_at   = now()
 WHERE metal_type = 'GOLD_14K'
   AND price_side = 'BUY'
   AND mode = 'DERIVED';

COMMENT ON COLUMN market_price_policies.derive_ratio IS
    '24K 환산 비율. 같은 금속이라도 살 때(판매)와 팔 때(매입)가 다르다 — 행마다 따로 둔다';
