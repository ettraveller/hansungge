-- V41__product_delivery.sql : 배송기간·택배사를 상품마다 정한다
--
-- 2026-11-05.
--
-- ---------------------------------------------------------------------
-- V33 의 판단을 뒤집는다
--
-- V33 은 "기간이 아니라 BOOLEAN"을 골랐다. 상품마다 주수를 넣게 하면 올릴
-- 때마다 판단해야 하고 6주를 넘기는 값이 들어가면 PG 정책 위반이 된다는
-- 이유였고, 그래서 재고 보유 / 주문제작 두 갈래로 고정했다.
--
-- 실제로는 그 두 문장이 <b>라디오 하나</b>로 갈렸다. 선택이 틀린 상품은
-- 「영업일 7일 이내」라는 지킬 수 없는 약속을 내걸었고, 같은 주문제작
-- 안에서도 제품마다 기간이 달랐다. V33 이 "실제로 기간이 다른 품목이 생기면
-- 그때 컬럼을 늘린다"고 적어 둔 그 자리다.
--
-- 택배사도 같다. 우체국택배 한 줄이 코드에 박혀 있었다.
--
-- ---------------------------------------------------------------------
-- NULL 은 "안 정했다"는 뜻이다. 빈 문자열이 아니다
--
-- NULL 이면 화면이 기본 문구를 쓴다 — 기간은 「상품별 상이 · 상세페이지
-- 참조」, 택배사는 「우체국택배」. 빈 문자열을 넣으면 화면에 빈 칸이 찍혀,
-- 고지가 없는 것인지 비워 둔 것인지 구분할 수 없다. 서버가 공백을 NULL 로
-- 접는다 (DeliveryNotice).
--
-- ---------------------------------------------------------------------
-- made_to_order 는 남는다
--
-- 기간과 함께 움직이던 값이지만 지우지 않는다. 그쪽이 결정하는 나머지
-- 하나가 <b>청약철회 제한 고지</b>이고, 그것은 전자상거래법 §17②① 단서가
-- 요구하는 고지라 상품마다 사실대로 켜져 있어야 한다.
--
-- ---------------------------------------------------------------------
-- ⚠️ 기간 고지 의무가 사라진 것이 아니다
--
-- "구매자가 배송기간을 인지할 수 있도록 상품페이지 내에 명확히 기재"(PG
-- 심사 요건), 전자상거래법 §13② 의 공급시기 고지. 비워 두는 상품은 상세
-- 이미지에 기간이 적혀 있어야 한다. 등록 화면이 그 사실을 적는다.
-- =====================================================================

ALTER TABLE products
    ADD COLUMN delivery_period VARCHAR(100),
    ADD COLUMN courier         VARCHAR(40);

COMMENT ON COLUMN products.delivery_period IS
    '이 상품의 배송기간 문구. NULL 이면 화면이 「상품별 상이 · 상세페이지 참조」를 쓴다';

COMMENT ON COLUMN products.courier IS
    '이 상품의 택배사. NULL 이면 화면이 「우체국택배」를 쓴다';
