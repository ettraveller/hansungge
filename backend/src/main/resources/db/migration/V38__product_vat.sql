-- =====================================================================
-- V38 — 부가세를 상품마다 정한다
--
-- 지금까지 부가세는 전역 설정 하나(system_settings.VAT_MODE)였고, 그 값이
-- 'TBD' 라서 전 상품이 면세로 동작했다. 그런데 이 가게가 파는 물건은 한 종류가
-- 아니다 — 금지금(골드바·순금)은 면세 요건이 있고, 가공한 주얼리는 과세다.
-- 설정 하나로는 둘을 동시에 맞출 수 없다. V19 이전 코드 주석이 이미 그 점을
-- 적어 두고 있었다("골드바(금지금) 면세 / 주얼리 과세 구분은 세무사 확인 대기").
--
-- 과세 상품의 판매가는 「부가세 포함」이다
--   표시가가 곧 받는 돈이고, 그 안에 얼마가 세금인지를 주문서·영수증에서
--   쪼개 보여 준다. 국내 주얼리 쇼핑몰의 통상적인 방식이고, 무엇보다
--   <b>이 변경으로 고객이 보는 가격이 한 푼도 바뀌지 않는다.</b>
--   (별도 부과였다면 과세 상품이 전부 10% 올라 보였을 것이다)
--
-- 세율은 상품마다 두지 않는다
--   세율은 법이 정하는 값이지 상품의 성질이 아니다. 상품마다 숫자를 받으면
--   오타 하나가 그대로 금액이 된다(1 을 10 으로, 100 을 10 으로). 설정값
--   VAT_RATE 하나로 두고, 상품은 과세인지 아닌지만 고른다.
--
-- 기본값을 FALSE(면세)로 두는 이유
--   지금 동작과 정확히 같다. 기본을 과세로 두면 이 마이그레이션 하나로 전
--   상품이 "부가세 포함"이라고 주장하게 되는데, 금지금 면세 요건은 까다로워
--   상품마다 다를 수 있다. 사람이 하나씩 켜는 편이 맞다.
-- =====================================================================

ALTER TABLE products
    ADD COLUMN vat_taxable BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN products.vat_taxable IS
    '과세 상품인가. TRUE 면 판매가에 부가세가 포함된 것으로 보고 공급가액/세액을 쪼갠다. '
    'FALSE 면 면세 — 세액 0, 최종가 = 소계. 세율은 system_settings.VAT_RATE 를 쓴다.';

-- 전역 설정은 더 이상 상품 가격을 정하지 않는다. 지워 두지는 않는다 —
-- 지난 주문의 스냅샷이 그 시절 정책으로 만들어졌고, 설정 이력을 남겨 둔다.
UPDATE system_settings
   SET value = 'PER_PRODUCT',
       description = '[V38] 상품별로 정한다(products.vat_taxable). 이 값은 더 이상 가격 계산에 쓰이지 않는다'
 WHERE key = 'VAT_MODE';

-- 세율. 없으면 만들어 둔다 — 코드 기본값(10)과 같게 두고, 바뀌면 여기만 고친다.
INSERT INTO system_settings(key, value, description)
VALUES ('VAT_RATE', '10', '부가세율(%). 과세 상품에만 적용된다')
ON CONFLICT (key) DO NOTHING;
