-- =====================================================================
-- V18 — 한 번 고시한 값은 새 고시가 나올 때까지 유효하다
--
-- 지금까지는 마지막 고시로부터 240분(4시간)이 지나면 금액을 감추고
-- "시세문의"로 바꿨다. 오래된 값으로 파는 위험을 막으려던 장치다.
--
-- 그런데 시간만 보면, 장이 닫혀 있는 동안에도 시간은 흐른다.
-- 금요일 저녁에 고시한 값은 토요일 새벽에 시세문의로 빠지고, 월요일 아침까지
-- 그대로다. 그 사이 값이 바뀔 이유가 없는데도 그렇다. 영업시간 뒤도 마찬가지라,
-- 실제로는 "고시가 끊긴 것"이 아니라 "아무 일도 없었던 것"에 시세문의가 붙는다.
--
-- 0 = 노후 판정 안 함. 수동이든 자동이든 마지막 고시값을 계속 최종 시세로 쓴다.
--
-- ⚠️ 대신 감수하는 것 — 수집이 며칠 죽어 있어도 옛 값으로 계속 팔린다.
--    판정 자체는 코드에 남아 있으므로, 되돌리려면 이 값을 분 단위 양수로
--    바꾸기만 하면 된다(예: 240). 재배포는 필요 없다.
-- =====================================================================

UPDATE system_settings
   SET value = '0',
       description = '0 = 마지막 고시값을 계속 쓴다(시간이 지나도 시세문의로 바뀌지 않음). '
                     || '양수를 넣으면 그 분(分)이 지난 뒤 금액을 감추고 "시세문의"로 바꾼다. '
                     || '장이 닫힌 주말·야간에도 시간은 흐르므로, 켤 때는 그 점을 감안할 것.',
       updated_at = now()
 WHERE key = 'PRICE_STALE_MINUTES';
