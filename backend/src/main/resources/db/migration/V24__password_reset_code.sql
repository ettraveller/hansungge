--   ① 문자 인증번호  — 가입 때 본인인증으로 명의가 확인된 번호. 싸다
--   ② 이메일 인증번호 — 인증을 마친 이메일이 있는 회원만
--   ③ 본인인증(간편인증) — 번호가 바뀌었거나 위 둘을 못 쓸 때. 건당 과금
--
-- 이메일 경로가 상대적으로 약한 것(메일 계정이 털리면 같이 털린다)은 알고 받아들인다.
-- 돈이 나가는 일(매입 신청·정산계좌 등록)은 비밀번호가 아니라 본인인증(STEP_UP)을 따로 요구하므로,
-- 비밀번호를 빼앗겨도 금전 피해 경로는 막혀 있다. 재설정하면 다른 기기 세션도 전부 끊긴다.
--
-- 인증번호 목적을 하나 더 받는다. 목적을 나누는 이유는 재사용을 막기 위해서다 —
-- 로그인하려고 받은 번호로 남의 비밀번호를 바꿀 수 있으면 안 된다.
