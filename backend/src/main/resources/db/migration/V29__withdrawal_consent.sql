-- =====================================================================
-- V29__withdrawal_consent.sql : 청약철회 제한 동의 기록
--
-- 2026-10-20. 이용안내(/guide)에 "시세 변동 상품이라 청약철회가 제한된다" 를 적어
-- 두었지만, 안내만으로는 효력이 약하다. 전자상거래법 제17조 제2항 단서는 사업자가
-- 그 사실을 <b>소비자가 쉽게 알 수 있는 곳에 명기</b>하지 않으면 제한이 성립하지
-- 않는다고 본다. 실무에서는 주문 시점에 동의를 받고 <b>그 기록을 남긴다</b> —
-- 분쟁이 났을 때 "안내했다" 가 아니라 "이 주문에서 동의했다" 를 보여야 하기 때문이다.
--
-- 그래서 주문에 함께 적는다. 동의 없이 만들어진 주문과 구분되어야 하므로
-- 기본값을 false 로 두고, 지나간 주문을 소급해 true 로 바꾸지 않는다 —
-- 받은 적 없는 동의를 받았다고 적는 것이기 때문이다.
-- =====================================================================

ALTER TABLE orders
    ADD COLUMN withdrawal_consent_at TIMESTAMPTZ;

COMMENT ON COLUMN orders.withdrawal_consent_at IS
    '청약철회 제한 안내에 동의한 시각. NULL 이면 동의를 받지 않고 만들어진 주문이다 (V29 이전)';
