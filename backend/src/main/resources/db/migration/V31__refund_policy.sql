-- =====================================================================
-- V31 — 환불규정 (교환·반품·환불 규정)
--
-- 결제 직전에 고객이 읽고 동의하는 문서다. 지금까지는 공지사항 글로만 있었는데,
-- 공지는 고치면 옛 내용이 사라진다. 동의는 "그때 그 고객이 본 바로 그 판"을
-- 가리킬 수 있어야 분쟁에서 쓸 수 있다 — 그래서 판마다 행을 쌓고, 한 번 쌓인
-- 판은 고치거나 지우지 못하게 한다 (시세 이력과 같은 append-only).
--
-- 관리자가 수정하면 새 판이 생기고, 쇼핑몰과 주문서는 항상 최신 판을 보여준다.
-- 주문은 동의한 판의 id 를 함께 적는다 (orders.refund_policy_id).
-- =====================================================================

CREATE TABLE refund_policies (
    id          BIGSERIAL    PRIMARY KEY,
    content     TEXT         NOT NULL CHECK (length(btrim(content)) > 0),
    change_note VARCHAR(200) NOT NULL,
    created_by  VARCHAR(60)  NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE refund_policies IS '교환·반품·환불 규정. 개정할 때마다 행을 쌓는다 (append-only)';
COMMENT ON COLUMN refund_policies.change_note IS '무엇을 왜 고쳤는가. 감사로그에도 함께 남는다';

-- 동의의 증거다. 지난 판을 고치면 "그때 동의한 내용"이 바뀌어 버린다.
CREATE OR REPLACE FUNCTION fn_refund_policy_guard() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'refund_policies is append-only (% forbidden)', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_refund_policy_guard
    BEFORE UPDATE OR DELETE ON refund_policies
    FOR EACH ROW EXECUTE FUNCTION fn_refund_policy_guard();

-- 주문이 어느 판에 동의했는가. NULL = 이 컬럼이 생기기 전 주문이다 —
-- 받은 적 없는 동의를 소급해 적지 않는다 (V29 와 같은 원칙).
ALTER TABLE orders
    ADD COLUMN refund_policy_id BIGINT REFERENCES refund_policies (id);

COMMENT ON COLUMN orders.refund_policy_id IS '주문 때 동의한 환불규정 판. NULL 이면 V31 이전 주문';

