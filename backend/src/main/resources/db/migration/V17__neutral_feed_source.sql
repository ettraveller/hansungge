-- V17 — 수집 원천 이름에서 특정 업체를 지운다
--
-- V14 가 넣은 'KGX' 는 특정 업체를 가리키는 약어였다. 그 업체의 API 를 긁는
-- 구현은 걷어냈고(약관 미확인 — TODO B-1), 남는 것은 "살 때·팔 때를 각각
-- 고시하는 원천"이라는 자리뿐이다. 자리에는 공급자 이름이 아니라 역할을 적는다.
--
-- 행 자체는 지우지 않는다. 지우면 raw 행의 source_id 참조가 끊기고, 이 자리를
-- 쓰는 코드 경로(짝 수집 → 짝 발행)도 함께 사라진다. 그 경로는 특정 공급자의
-- 사정이 아니라 "금값이 움직이면 살 때·팔 때가 같이 움직인다"는 원칙에서 나온
-- 것이라 공급자가 바뀌어도 그대로 쓰인다.
--
-- active 는 FALSE 그대로다. 구현체가 없으므로 켜도 아무 일도 일어나지 않는다.
-- =====================================================================

UPDATE market_price_sources
   SET code = 'AUTO_FEED',
       name = '자동 수집 원천 (살 때·팔 때 동시 고시). 공급자 미정 — TODO B-1'
 WHERE code = 'KGX';
