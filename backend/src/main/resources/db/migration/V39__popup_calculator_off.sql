-- V39 — 매입 계산기 팝업을 내린다
--
-- V37 이 시드로 켜 둔 팝업이다. 첫 화면에서 빼기로 했다.
--
-- 지우지 않고 끈다. 행을 지우면 관리자 화면의 팝업 목록이 비고, 다음에
-- 띄울 때 기간·링크·문구를 처음부터 다시 적어야 한다. 끄기는 관리자
-- 화면에서 되돌릴 수 있다 (관리자 › 팝업).
--
-- 기능은 그대로 둔다 — 팝업 틀(V37)과 관리 화면은 이벤트·휴무 안내에
-- 쓰려고 만든 것이고, 지금 내리는 것은 그 틀에 들어 있던 한 건이다.
--
-- 이름이 아니라 kind + created_by 로 찾는다. 관리자가 이름을 바꿨으면
-- 이름으로는 못 찾고, 그러면 아무 일도 일어나지 않은 채 배포가 끝난다.
-- =====================================================================

UPDATE popups
   SET active     = FALSE,
       updated_by = 'system',
       updated_at = now()
 WHERE kind       = 'CALCULATOR'
   AND created_by = 'system'
   AND active;
