package com.hanseongge.domain.banner.entity;

/**
 * 배너를 만드는 두 가지 길 (V45).
 *
 * <p>둘을 한 표에 두는 이유는 <b>순서가 섞이기 때문</b>이다. 메인 맨 위에서 돌아가는
 * 자리는 하나이고, 사진 배너와 꾸민 배너가 번갈아 나올 수 있어야 한다. 표를 나누면
 * 그 순서를 두 표에 걸쳐 매겨야 한다.
 */
public enum BannerKind {

    /**
     * 사진 한 장이 전부인 배너.
     *
     * <p>문구·버튼까지 이미지 안에 들어간다. 디자이너가 만든 그림을 그대로 거는
     * 길이라 가장 자유롭고, 대신 글자 한 줄을 고치려면 사진을 다시 받아야 한다.
     */
    IMAGE,

    /**
     * 화면에서 꾸민 배너.
     *
     * <p>배경(색·사진·흐림) 위에 글자와 버튼을 쌓는다. 글자를 그 자리에서 고칠 수
     * 있고, 좌표가 없으므로 PC 와 휴대폰이 같은 내용으로 각자 맞게 그려진다.
     */
    DESIGN
}
